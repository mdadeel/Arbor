// @vitest-environment jsdom
import React from 'react'
import { describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { OwnershipMapCard } from './ownership-map'

describe('OwnershipMapCard', () => {
  it('renders directory bus factors, GitHub tree links, suggested CODEOWNERS, and copies to clipboard', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.assign(navigator, {
      clipboard: { writeText },
    })

    const rawOwnership = {
      commitsAnalyzed: 42,
      windowDays: 180,
      totalContributors: 3,
      overallBusFactor: 2,
      overallRisk: 'medium',
      existingCodeownersPath: null,
      defaultOwners: ['@mdadeel', '@alice'],
      directories: [
        {
          directory: 'src',
          pattern: '/src/',
          fileCount: 120,
          commits: 34,
          linesChanged: 2150,
          contributorCount: 2,
          busFactor: 1,
          risk: 'high',
          owners: [
            {
              codeowner: '@mdadeel',
              displayName: 'Adeel',
              email: '64582744+mdadeel@users.noreply.github.com',
              commits: 28,
              linesChanged: 1800,
              sharePercent: 79,
              lastCommitAt: '2026-10-25T10:00:00.000Z',
            },
            {
              codeowner: '@alice',
              displayName: 'Alice',
              email: 'alice@users.noreply.github.com',
              commits: 6,
              linesChanged: 350,
              sharePercent: 21,
              lastCommitAt: '2026-10-20T10:00:00.000Z',
            },
          ],
          suggestedOwners: ['@mdadeel', '@alice'],
        },
        {
          directory: 'docs',
          pattern: '/docs/',
          fileCount: 4,
          commits: 0,
          linesChanged: 0,
          contributorCount: 0,
          busFactor: 0,
          risk: 'unknown',
          owners: [],
          suggestedOwners: [],
        },
      ],
      suggestedCodeowners:
        '# Suggested CODEOWNERS generated by Arbor from git commit history\n* @mdadeel @alice\n/src/ @mdadeel @alice\n',
    }

    render(
      <OwnershipMapCard
        rawOwnership={rawOwnership}
        repoUrl="https://github.com/mdadeel/Arbor"
        commitSha="efef02783d86402dd62d6549ca30481a3d2881b4"
      />
    )

    expect(screen.getByText('Ownership Map & Directory Bus Factor')).toBeTruthy()
    expect(screen.getByText('Repo bus factor: 2')).toBeTruthy()
    expect(screen.getByText('Missing CODEOWNERS')).toBeTruthy()
    expect(screen.getByText('Single owner')).toBeTruthy()
    expect(screen.getByText('79%')).toBeTruthy()
    expect(screen.getByText('Inherits *')).toBeTruthy()

    const srcLink = screen.getByRole('link', { name: '/src/' })
    expect(srcLink.getAttribute('href')).toBe(
      'https://github.com/mdadeel/Arbor/tree/efef02783d86402dd62d6549ca30481a3d2881b4/src'
    )

    const copyBtn = screen.getByRole('button', { name: /Copy CODEOWNERS/i })
    fireEvent.click(copyBtn)
    await waitFor(() => {
      expect(writeText).toHaveBeenCalledWith(rawOwnership.suggestedCodeowners)
    })
  })

  it('renders nothing for legacy analyses without ownership telemetry', () => {
    const { container } = render(<OwnershipMapCard rawOwnership={undefined} />)
    expect(container.firstChild).toBeNull()
  })
})
